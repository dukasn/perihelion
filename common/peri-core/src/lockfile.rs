use std::collections::BTreeMap;

use semver::{Version, VersionReq};
use serde::{Deserialize, Serialize};

use crate::error::ResolveError;

pub const LOCKFILE_FILENAME: &str = "peri.lock";

/// Represents a deterministic, frozen resolution lockfile (`peri.lock`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Lockfile {
    pub version: u32,
    #[serde(default)]
    pub package: Vec<LockedPackage>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockedPackage {
    pub name: String,
    pub version: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub checksum: Option<String>,
}

impl Default for Lockfile {
    fn default() -> Self {
        Self {
            version: 1,
            package: Vec::new(),
        }
    }
}

impl Lockfile {
    pub fn new() -> Self {
        Self::default()
    }

    /// Creates a lockfile directly from a resolved solution map `(name -> version)`.
    pub fn from_solution(solution: &BTreeMap<String, Version>) -> Self {
        let mut packages = Vec::new();
        for (name, version) in solution {
            packages.push(LockedPackage {
                name: name.clone(),
                version: version.to_string(),
                checksum: None,
            });
        }
        packages.sort_by(|a, b| a.name.cmp(&b.name));

        Self {
            version: 1,
            package: packages,
        }
    }

    /// Returns a map of package name to parsed `semver::Version`.
    pub fn package_map(&self) -> BTreeMap<String, Version> {
        let mut map = BTreeMap::new();
        for pkg in &self.package {
            if let Ok(v) = Version::parse(&pkg.version) {
                map.insert(pkg.name.clone(), v);
            }
        }
        map
    }

    /// Verifies if this lockfile satisfies the given root requirements.
    pub fn satisfies_requirements(&self, root_dependencies: &BTreeMap<String, String>) -> bool {
        let map = self.package_map();
        for (dep_name, req_str) in root_dependencies {
            let Some(installed_version) = map.get(dep_name) else {
                return false;
            };
            if let Ok(req) = VersionReq::parse(req_str) {
                if !req.matches(installed_version) {
                    return false;
                }
            } else {
                return false;
            }
        }
        true
    }

    /// Parses a lockfile from a TOML string.
    pub fn from_toml_str(input: &str) -> Result<Self, ResolveError> {
        toml::from_str(input)
            .map_err(|e| ResolveError::UnsolvableConstraints(format!("Invalid peri.lock: {e}")))
    }

    /// Serializes the lockfile to a formatted TOML string with standard header.
    pub fn to_toml_str(&self) -> Result<String, ResolveError> {
        let toml_data = toml::to_string_pretty(self)
            .map_err(|e| ResolveError::UnsolvableConstraints(e.to_string()))?;
        Ok(format!(
            "# This file is automatically generated by Perihelion.\n# Do not edit manually.\n\n{toml_data}"
        ))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_lockfile_serde_roundtrip() {
        let mut solution = BTreeMap::new();
        solution.insert("cet".to_string(), Version::parse("1.30.0").unwrap());
        solution.insert("redscript".to_string(), Version::parse("0.5.15").unwrap());

        let lock = Lockfile::from_solution(&solution);
        let serialized = lock.to_toml_str().expect("should serialize lockfile");

        assert!(serialized.contains("cet"));
        assert!(serialized.contains("1.30.0"));
        assert!(serialized.contains("redscript"));

        let deserialized = Lockfile::from_toml_str(&serialized).expect("should parse lockfile");
        assert_eq!(lock, deserialized);
    }

    #[test]
    fn test_lockfile_satisfies_requirements() {
        let mut solution = BTreeMap::new();
        solution.insert("cet".to_string(), Version::parse("1.30.0").unwrap());

        let lock = Lockfile::from_solution(&solution);

        let mut reqs = BTreeMap::new();
        reqs.insert("cet".to_string(), ">=1.20, <2.0".to_string());
        assert!(lock.satisfies_requirements(&reqs));

        reqs.insert("cet".to_string(), ">=2.0".to_string());
        assert!(!lock.satisfies_requirements(&reqs));

        reqs.insert("missing_mod".to_string(), "*".to_string());
        assert!(!lock.satisfies_requirements(&reqs));
    }
}
