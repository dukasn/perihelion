//! Machine-Readable Report Data Transfer Objects (DTOs)
//!
//! Provides deterministic, structured serializable reports for CI automation,
//! headless runners, daemon integrations, and pipeline monitoring.

use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::path::PathBuf;

use crate::manifest::Priority;

/// Target output serialization format.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, Default)]
#[serde(rename_all = "snake_case")]
pub enum OutputFormat {
    #[default]
    Text,
    Json,
}

/// Structured report generated by `peri check --format json`.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct CheckReport {
    pub success: bool,
    pub game_id: String,
    pub package_count: usize,
    pub active_layers: Vec<ResolvedPackageSummary>,
    pub file_conflicts: Vec<FileConflictSummary>,
    pub has_unresolved_conflicts: bool,
}

/// Package layer summary inside a resolved check report.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ResolvedPackageSummary {
    pub name: String,
    pub version: String,
    pub priority: Priority,
    pub path_in_lowerdir: Option<PathBuf>,
}

/// File collision detail reported during Virtual File Index analysis.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct FileConflictSummary {
    pub relative_path: String,
    pub winning_package: String,
    pub shadowed_packages: Vec<String>,
    /// Resolution mechanism applied ("explicit_edge", "priority_weight", or "unresolved")
    pub resolution_tier: String,
}

/// Structured execution plan generated by `peri run --dry-run --format json`.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct DryRunPlanReport {
    pub game_id: String,
    pub base_game_path: PathBuf,
    pub mount_point: PathBuf,
    pub lowerdir: Vec<PathBuf>,
    pub upper_dir: PathBuf,
    pub work_dir: PathBuf,
    pub mount_options_string: String,
    pub executable: PathBuf,
    pub arguments: Vec<String>,
    pub environment: HashMap<String, String>,
}

/// Structured game profile summary for `peri profile list --format json`.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ProfileSummaryReport {
    pub id: String,
    pub name: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub steam_app_id: Option<u64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub default_executable: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub game_path: Option<PathBuf>,
    pub source_tier: String,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_check_report_json_roundtrip() {
        let report = CheckReport {
            success: true,
            game_id: "skyrim_se".to_string(),
            package_count: 2,
            active_layers: vec![
                ResolvedPackageSummary {
                    name: "skse64".to_string(),
                    version: "2.2.6".to_string(),
                    priority: Priority::Default,
                    path_in_lowerdir: Some(PathBuf::from(
                        "/workspace/.perihelion/extracted/skse64",
                    )),
                },
                ResolvedPackageSummary {
                    name: "skyui".to_string(),
                    version: "5.2.0".to_string(),
                    priority: Priority::High,
                    path_in_lowerdir: Some(PathBuf::from("/workspace/.perihelion/extracted/skyui")),
                },
            ],
            file_conflicts: vec![FileConflictSummary {
                relative_path: "Data/Interface/skyui.swf".to_string(),
                winning_package: "skyui".to_string(),
                shadowed_packages: vec!["skse64".to_string()],
                resolution_tier: "priority_weight".to_string(),
            }],
            has_unresolved_conflicts: false,
        };

        let json = serde_json::to_string(&report).expect("Serialize report");
        let parsed: CheckReport = serde_json::from_str(&json).expect("Deserialize report");
        assert_eq!(report, parsed);
        assert!(json.contains("skyui.swf"));
        assert!(!parsed.has_unresolved_conflicts);
    }

    #[test]
    fn test_dry_run_plan_report_json_roundtrip() {
        let mut env = HashMap::new();
        env.insert("WINEPREFIX".to_string(), "/compat/pfx".to_string());

        let report = DryRunPlanReport {
            game_id: "cyberpunk_2077".to_string(),
            base_game_path: PathBuf::from("/games/cyberpunk"),
            mount_point: PathBuf::from("/mnt/sandbox"),
            lowerdir: vec![
                PathBuf::from("/mods/cet"),
                PathBuf::from("/games/cyberpunk"),
            ],
            upper_dir: PathBuf::from("/tmp/upper"),
            work_dir: PathBuf::from("/tmp/work"),
            mount_options_string: "lowerdir=/mods/cet:/games/cyberpunk".to_string(),
            executable: PathBuf::from("bin/x64/Cyberpunk2077.exe"),
            arguments: vec!["-skipStartScreen".to_string()],
            environment: env,
        };

        let json = serde_json::to_string_pretty(&report).expect("Serialize dry-run report");
        let parsed: DryRunPlanReport =
            serde_json::from_str(&json).expect("Deserialize dry-run report");
        assert_eq!(report, parsed);
        assert!(json.contains("Cyberpunk2077.exe"));
    }

    #[test]
    fn test_profile_summary_report_json_roundtrip() {
        let report = ProfileSummaryReport {
            id: "starfield".to_string(),
            name: "Starfield".to_string(),
            steam_app_id: Some(1716740),
            default_executable: Some("Starfield.exe".to_string()),
            game_path: Some(PathBuf::from("/games/starfield")),
            source_tier: "user_config".to_string(),
        };

        let json = serde_json::to_string(&report).expect("Serialize profile report");
        let parsed: ProfileSummaryReport =
            serde_json::from_str(&json).expect("Deserialize profile report");
        assert_eq!(report, parsed);
        assert!(json.contains("1716740"));
    }
}
